CREATE TABLE study_session (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(160) NOT NULL,
    description varchar(1200) NOT NULL,
    starts_at timestamptz NOT NULL,
    closes_at timestamptz NOT NULL,
    capacity integer NOT NULL CHECK (capacity BETWEEN 1 AND 200),
    CHECK (closes_at < starts_at)
);
CREATE TABLE registration (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL REFERENCES study_session(id),
    member_subject varchar(255) NOT NULL CHECK (length(trim(member_subject)) > 0),
    created_at timestamptz NOT NULL,
    CONSTRAINT registration_session_member_unique UNIQUE (session_id,member_subject)
);
GRANT SELECT ON study_session TO study_app;
-- PostgreSQL FOR UPDATE requires UPDATE on at least one column. Policy columns remain read-only.
GRANT UPDATE(id) ON study_session TO study_app;
GRANT SELECT,INSERT ON registration TO study_app;
GRANT USAGE ON SEQUENCE registration_id_seq TO study_app;
